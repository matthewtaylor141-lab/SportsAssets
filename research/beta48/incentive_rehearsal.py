def _manifest_file(n_markets: int, et_date: str, path: str) -> str:
    progs = [{"market_slug": "rehearsal-market-%02d" % i,
              "program_id": "culture_low_20260921",
              "created_at": "2026-09-21T00:00:00Z",
              "period": man.PERIOD_DAILY, "reward_pool": 50.0,
              "discount_factor": 0.25, "target_size": 500,
              "start": et_date + "T04:00:00Z", "end": et_date + "T04:00:00Z",
              "status": "active",
              "event_start_time": "2026-12-27T04:59:00.000Z",
              "instrument_state": "INSTRUMENT_STATE_OPEN",
              "category": "culture"} for i in range(n_markets)]
    m = {"manifest": man.MANIFEST_VERSION,
         "manifest_id": "REHEARSAL%02d" % n_markets,
         "captured_at": datetime.now(timezone.utc).isoformat(),
         "source": man.INCENTIVES_URL, "authenticated": False,
         "response_digest": "sha256:REHEARSAL-FIXTURE-NOT-VENUE-CAPTURED",
         "et_date": et_date, "pages_read": 0,
         "FIXTURE": "SYNTHETIC. These slugs do not exist at the venue and "
                    "these terms were not retrieved from it.",
         "programs": progs}
    man.save(path, m)
    return path


