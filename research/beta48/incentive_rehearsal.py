"""The rehearsal, driven through the REAL no-argument entry point.

WHAT MAKES THIS A REHEARSAL AND NOT A UNIT TEST. Every scenario calls
`bettor_live_loop.main()` WITH NO ARGUMENTS -- the exact call
`workers/all.py` makes in production. Nothing is injected through a
keyword, because a keyword is a seam production never uses and the
2026-09-22 NO_CONTROL_POOL failure came from exactly that: every local
proof had passed a pool, so the None-resolving path the service
actually takes had never been exercised and refused its first
reservation in the live probe.

    the entry point     `bettor_live_loop.main()`          -- real
    the mode switch     the process environment            -- real
    the control         Postgres `ingestion_state`         -- real
    the allowlist       a manifest file on disk            -- real
    the budget ledger   seeded from the real run row       -- real
    the journal         real files, real fsync             -- real

    THE TRANSPORT       A FAKE. `bettor_market_stream.MarketStream` is
                        replaced in THIS PROCESS by `FakeStream`. NO
                        SOCKET IS OPENED, NO VENUE BYTE IS RECEIVED,
                        AND NO CREDENTIAL IS USED -- the key id and
                        secret below are the literal strings
                        "REHEARSAL-KEY-ID" and "REHEARSAL-SECRET",
                        invented here and handed to a class that
                        ignores them. Every frame in the output was
                        generated by the loop below. The one thing this
                        rehearsal therefore CANNOT establish is that
                        the venue's socket behaves as `MarketStream`
                        assumes.

    THE CREDENTIAL CHECK is still real: scenario S0 runs with the
    placeholders removed and shows the runner refusing to start.

Run:  python research/beta48/incentive_rehearsal.py
"""
