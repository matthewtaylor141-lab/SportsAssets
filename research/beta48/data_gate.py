    w("The four-account x frozen first-leg-bucket table, because it is the")
    w("only thing that separates the four explanations still standing for")
    w("why the pair channel changes sign. Right now")
    w("`PAIR_MECHANISM_CROSS_ACCOUNT_REPLICATION` cannot be called: the")
    w("sign splits 3/3, and a split is equally consistent with")
    w("STRUCTURAL_DISCRIMINATOR, ACCOUNT_SELECTION_PROXY, MARKET_MIX_PROXY")
