#!/usr/bin/env python3
"""BETA48_DATA_GATE — is the six-account comparison admissible, and for what?

READ ONLY, OFFLINE. Reads the sealed reconstructions and writes
research/beta48/BETA48_DATA_GATE.md with exactly the thirteen fields the
directive names, in that order. Contacts nothing. Changes no estimator.

Every number in the output is COMPUTED from the sealed JSONs. The
judgement fields (YES / NO / PARTIAL) are decided by explicit rules
stated in the code below, so the verdict can be re-derived and argued
with rather than taken on trust.

THE RECONCILIATION TARGETS are the directive's own report-derived
hypotheses, which name two channels per account:

    "matched"     -> the pair/merge channel   (MERGE_PNL here)
    "directional" -> the held-to-settlement channel (SETTLED_PNL here)

Those are the same two channels channel_decomposition.py splits lot_s
and lot_p into, so the comparison is like-for-like.
"""

from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
BLOBS = HERE / "evidence" / "blobs"

# The directive's report-derived hypotheses, verbatim in intent:
#   Ferrari  matched ~+$17.2M / +5.9%   directional ~-$16.2M / -7.7%
#   HRH      matched  ~-$1.35M / -1.5%  directional  ~+$2.46M / +3.3%
#   swisstony matched ~-$3.39M / -0.7%  directional ~+$22.16M / +4.2%
HYPOTHESES = {
    "ferrarichampions2026": {"matched": (17.2e6, 0.059), "directional": (-16.2e6, -0.077)},
    "homerunhazard":        {"matched": (-1.35e6, -0.015), "directional": (2.46e6, 0.033)},
    "swisstony":            {"matched": (-3.39e6, -0.007), "directional": (22.16e6, 0.042)},
}

# RN1's retained-snapshot measurement, for the two-source comparison.
RN1_SNAPSHOT = {"edge_roi": 0.02084, "ci": (-0.00195, 0.04362),
                "fills": 196619, "merges": 78500,
                "sample": "2026-08-06 .. 2026-09-11"}

ACCOUNTS = ("rn1", "w2c33", "homerunhazard", "swisstony", "kch123",
            "ferrarichampions2026")
# A rate agreeing within this many percentage points is "consistent".
RATE_TOL_PP = 2.5


def load(name):
    p = BLOBS / ("%s_reconstruction.json" % name)
    return json.loads(p.read_text()) if p.exists() else None


def decompose(r):
    """Same split as channel_decomposition.py, re-derived here so this
    file stands alone as evidence."""
    lot_s, lot_p = r["lot_s"], r["lot_p"]
    merge = r.get("realized_merge_pnl") or 0.0
    sell = r.get("realized_sell_pnl") or 0.0
    st_stake = (r.get("open_cost") or 0.0) - (r.get("ungraded_open_cost") or 0.0)
    st_pnl = lot_p - merge - sell
    tr_stake = lot_s - st_stake
    assert abs(st_stake + tr_stake - lot_s) < 0.01
    assert abs(st_pnl + merge + sell - lot_p) < 0.01
    return {"merge_pnl": merge, "merge_rate": merge / tr_stake if tr_stake else None,
            "traded_stake": tr_stake,
            "settled_pnl": st_pnl, "settled_rate": st_pnl / st_stake if st_stake else None,
            "settled_stake": st_stake}


def reconcile(name, d):
    """Compare a channel against the report hypothesis. Sign first,
    then rate. A sign disagreement is material however small the number,
    because the sign is what the mechanism claim rests on."""
    h = HYPOTHESES.get(name)
    if not h:
        return None
    out = {}
    for chan, (h_pnl, h_rate) in h.items():
        m_pnl = d["merge_pnl"] if chan == "matched" else d["settled_pnl"]
        m_rate = d["merge_rate"] if chan == "matched" else d["settled_rate"]
        same_sign = (m_pnl >= 0) == (h_pnl >= 0)
        gap_pp = abs((m_rate or 0) - h_rate) * 100
        if not same_sign:
            verd = "SIGN_DISAGREES"
        elif gap_pp <= RATE_TOL_PP:
            verd = "CONSISTENT"
        else:
            verd = "SIGN_AGREES_MAGNITUDE_DIFFERS"
        out[chan] = {"measured_pnl": round(m_pnl, 2),
                     "measured_rate": round(m_rate, 5) if m_rate is not None else None,
                     "report_pnl": h_pnl, "report_rate": h_rate,
                     "gap_pp": round(gap_pp, 2), "verdict": verd}
    return out


